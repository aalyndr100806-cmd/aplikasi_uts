package com.alya_nadira_f52124011.aplikasi_uts;

public class Teman {

    String nama;
    String nim;
    String kelas;
    String email;
    int foto;

    public Teman(
            String nama,
            String nim,
            String kelas,
            String email,
            int foto) {

        this.nama = nama;
        this.nim = nim;
        this.kelas = kelas;
        this.email = email;
        this.foto = foto;
    }
}